import assert from 'node:assert/strict'
import { after, test } from 'node:test'
import { deferred, teardown, load, install, mock } from '../../../scripts/harness.mjs'

after(teardown)
const { Resource } = await load('shared/resource.svelte.ts')
const settle = () => Promise.resolve()

test('refresh keeps the last result, including on failure, then accepts a retry', async () => {
  const view = new Resource()
  const old = [1, 2]
  view.watch(Promise.resolve(old), 'thread')
  await settle()
  const refresh = deferred()
  view.watch(refresh.promise, 'thread')
  assert.equal(view.result.value, old)
  assert.equal(view.pending, true)
  refresh.reject(new Error('busy'))
  await settle()
  assert.equal(view.result.value, old)
  assert.equal(view.error.cause.message, 'busy')
  view.watch(Promise.resolve([1, 2, 3]), 'thread')
  await settle()
  assert.deepEqual(view.result.value, [1, 2, 3])
  assert.equal(view.error, null)
  assert.equal(view.pending, false)
})

test('a late success or failure cannot replace a newer account or request', async () => {
  const view = new Resource()
  const old = deferred(), newer = deferred()
  view.watch(old.promise, 'alice')
  view.watch(newer.promise, 'bob')
  newer.resolve(['bob'])
  await settle()
  old.resolve(['alice'])
  await settle()
  assert.deepEqual(view.result, { key: 'bob', value: ['bob'] })
  const stale = deferred()
  view.watch(stale.promise, 'bob')
  view.watch(Promise.resolve(['new bob']), 'bob')
  await settle()
  stale.reject(new Error('old failure'))
  await settle()
  assert.deepEqual(view.result.value, ['new bob'])
  assert.equal(view.error, null)
})

test('an unmounted view ignores completion, and an old cleanup cannot cancel its successor', async () => {
  const view = new Resource()
  const gone = deferred()
  const cancel = view.watch(gone.promise, 'first')
  cancel()
  gone.resolve('gone')
  await settle()
  assert.equal(view.result, null)
  view.watch(Promise.resolve('current'), 'next')
  cancel()
  await settle()
  assert.deepEqual(view.result, { key: 'next', value: 'current' })
})

test('a settled result stands: a request still out cannot undo it, and a failure on show is cleared', async () => {
  const view = new Resource()
  const slow = deferred()
  view.watch(slow.promise, 'alice')
  view.settle('alice', true)
  assert.equal(view.value('alice'), true)
  assert.equal(view.pending, false)
  slow.resolve(false)
  await settle()
  assert.equal(view.value('alice'), true, 'the read that was out when the action happened cannot undo it')
  view.watch(Promise.reject(new Error('busy')), 'alice')
  await settle()
  assert.equal(view.failure('alice').cause.message, 'busy')
  view.settle('alice', false)
  assert.equal(view.failure('alice'), null)
  assert.equal(view.value('alice'), false)
})

test('a result settled for a key the view has moved on from is dropped, and the newer key’s read goes on', async () => {
  const view = new Resource()
  const alice = deferred(), bob = deferred()
  view.watch(alice.promise, 'alice') // Alice presses unblock; her read is still out
  view.watch(bob.promise, 'bob') // the wallet switches to Bob before the chain confirms
  view.settle('alice', false) // Alice's unblock confirms
  assert.equal(view.value('alice'), null, 'not shown: the page is Bob’s now')
  assert.equal(view.value('bob'), null)
  bob.resolve(true)
  await settle()
  assert.equal(view.value('bob'), true, 'Bob’s read was not cancelled by Alice’s result')
  alice.resolve(false)
  await settle()
  assert.equal(view.value('bob'), true)
})


test('only a current rendered result is acknowledged, including after switching back to the same account', async () => {
  const view = new Resource(), shown = []
  const flush = () => new Promise(setImmediate)
  const old = deferred(), bob = deferred(), latest = deferred()
  view.watch(old.promise, 'alice', value => shown.push(value))
  view.watch(bob.promise, 'bob', value => shown.push(value))
  view.watch(latest.promise, 'alice', value => shown.push(value))
  old.resolve('stale alice'); bob.resolve('stale bob')
  await flush()
  assert.deepEqual(shown, [])
  latest.resolve('current alice')
  await flush()
  assert.deepEqual(shown, ['current alice'])
  const gone = deferred()
  const stop = view.watch(gone.promise, 'alice', value => shown.push(value))
  stop(); gone.resolve('unmounted')
  await flush()
  assert.deepEqual(shown, ['current alice'])
  view.watch(Promise.reject(Error('failed')), 'alice', value => shown.push(value))
  await flush()
  assert.deepEqual(shown, ['current alice'])
})
