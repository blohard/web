test('a show-more control breaks adjacency even when the parent is the last loaded card', async ({ page, host }) => {
  const root = host.post(1, 'Root')
  for (let i = 2; i <= 22; i++) host.post(i, `Direct reply ${i}`, { parent: 1 })
  const child = host.post(23, 'Retained child of last loaded parent', { parent: 21 })
  await mount(page, host, { root: { id: 1, post: root, drawn: 0, joins: false }, cards: [preview(child, 0, false, true)], counts: [[1, 21], [23, 0]] })
  await expect(card(page, 23)).toBeVisible()
  await card(page, 1).getByRole('button', { name: '21 replies', exact: true }).click()
  await expect(card(page, 21)).toBeVisible()
  await expect(page.getByRole('button', { name: '[ show 1 more reply ]', exact: true })).toBeVisible()
  await expect(page.getByRole('link', { name: 'in reply to #21', exact: true })).toBeVisible()
  await expect(card(page, 21)).not.toHaveClass(/\bconnector\b/)
  await expect(card(page, 23)).toHaveCount(1)
})

test('muting an expanded reply preserves its connector to its open replies', async ({ page, host }) => {
  await setup(page, host)
  await card(page, 230).getByRole('button', { name: '1 more reply', exact: true }).click()
  await card(page, 233).getByRole('button', { name: '1 more reply', exact: true }).click()
  await expect(card(page, 235)).toBeVisible()
  await expect(card(page, 233)).toHaveClass(/\bconnector\b/)
  await page.evaluate(async address => {
    const { muted } = await import('/src/lib/muted.svelte.ts')
    muted.toggle(address)
  }, stranger)
  await expect(card(page, 233)).toHaveClass(/\bcollapsed\b/)
  await expect(card(page, 233)).toHaveClass(/\bconnector\b/)
  await expect(card(page, 233).locator('.line:not(.up)')).toBeVisible()
  await expect(card(page, 234)).toBeVisible()
  await expect(card(page, 235)).toBeVisible()
})
