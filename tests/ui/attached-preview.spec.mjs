import { test, expect, card, deferred, stranger } from './host.mjs'
const preview = (post, drawn = 0, joins = false, gap = false) => ({ post, drawn, joins, gap })
const ids = page => page.locator('article.msg a[aria-label^="open post #"]').evaluateAll(links => links.map(a => Number(a.textContent.slice(1))))
async function mount(page, host, props) {
  await page.addInitScript(props => { window.conversation = props }, { chain: host.chain, at: host.at, ...props })
  await page.goto('/tests/ui/fixtures/conversation.html')
}
async function setup(page, host, slow = false, laterSibling = false) {
  if (slow) host.chain.blocklist = { registry: host.chain.contract, list: 'blocked' }
  const root = host.post(230, 'Root')
  host.post(231, 'Additional reply', { parent: 230 })
  const parent = host.post(233, 'Preview parent', { parent: 230, who: stranger })
  const child = host.post(234, 'Kept child', { parent: 233 })
  host.post(235, 'Additional child', { parent: 233 })
  if (laterSibling) host.post(236, 'Later sibling', { parent: 230 })
  await mount(page, host, { root: { id: 230, post: root, drawn: 1, joins: true }, cards: [preview(parent, 1, true), preview(child)], editor: 233, counts: [[230, laterSibling ? 3 : 2], [233, 2], [234, 0]] })
  await expect(card(page, 234)).toBeVisible()
}
test('adjacent parent and preview connect without reordering or reading the child branch', async ({ page, host }) => {
  const reads = []
  await page.route('**/replies', async route => { reads.push(route.request().postDataJSON().parent); await route.fallback() })
  await setup(page, host)
  await card(page, 230).getByRole('button', { name: '1 more reply', exact: true }).click()
  await expect.poll(() => ids(page)).toEqual([230, 231, 233, 234])
  await expect(page.getByRole('link', { name: 'in reply to #233', exact: true })).toHaveCount(0)
  await expect(card(page, 233)).toHaveClass(/\bconnector\b/)
  expect(reads).toEqual(['230'])
  await card(page, 233).getByRole('button', { name: '1 more reply', exact: true }).click()
  await expect.poll(() => ids(page)).toEqual([230, 231, 233, 234, 235])
  expect(reads).toEqual(['230', '233'])
  await card(page, 233).getByRole('button', { name: 'hide replies', exact: true }).click()
  await expect.poll(() => ids(page)).toEqual([230, 231, 233])
})
test('a kept child attaches only when paging brings its parent into the list', async ({ page, host }) => {
  const root = host.post(1, 'Root')
  for (let i = 2; i <= 25; i++) host.post(i, `Reply ${i}`, { parent: 1 })
  const parent = host.post(26, 'Late parent', { parent: 1 })
  const child = host.post(27, 'Kept child', { parent: 26 })
  const reads = []
  await page.route('**/replies', async route => { reads.push(route.request().postDataJSON().parent); await route.fallback() })
  await mount(page, host, { root: { id: 1, post: root, drawn: 0, joins: false }, cards: [preview(child, 0, false, true)], gates: [parent], counts: [[1, 25], [27, 0]] })
  await expect(card(page, 27)).toBeVisible()
  await card(page, 1).getByRole('button', { name: '25 replies', exact: true }).click()
  await expect(card(page, 21)).toBeVisible()
  await expect(card(page, 26)).toHaveCount(0)
  await expect(page.getByRole('link', { name: 'in reply to #26', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '[ show 5 more replies ]', exact: true }).click()
  await expect(card(page, 26)).toBeVisible()
  await expect(card(page, 27)).toHaveCount(1)
  await expect(page.getByRole('link', { name: 'in reply to #26', exact: true })).toHaveCount(0)
  expect(reads).toEqual(['1', '1'])
})
for (const terminal of ['1', '2']) test(`deleting or removing an attached parent (${terminal}) detaches its surviving preview`, async ({ page, host }) => {
  await setup(page, host)
  await card(page, 230).getByRole('button', { name: '1 more reply', exact: true }).click()
  await expect.poll(() => ids(page)).toEqual([230, 231, 233, 234])
  await page.evaluate(async ({ chain, terminal }) => {
    const { gates } = await import('/src/lib/gates.svelte.ts')
    gates.settleMessage(chain, 233n, `0x${terminal.padStart(40, '0')}`, { block: 1000n, index: 0 })
  }, { chain: host.chain, terminal })
  await expect(card(page, 233)).toHaveCount(0)
  await expect(card(page, 234)).toBeVisible()
  await expect(page.getByRole('link', { name: /in reply to #233.*(?:deleted|removed)/ })).toBeVisible()
})
test('a pending parent keeps its attached preview labelled after the display timeout', async ({ page, host }) => {
  await setup(page, host, true)
  const started = deferred(), release = deferred()
  await page.route('**/state', async route => {
    if (!route.request().postDataJSON().memberships?.some(m => m.member.toLowerCase() === stranger.toLowerCase())) return route.fallback()
    started.resolve(); await release.promise; await route.fallback()
  })
  try {
    await card(page, 230).getByRole('button', { name: '1 more reply', exact: true }).click()
    await started.promise
    await expect(page.locator('.reply-list').first()).not.toHaveClass(/preparing/, { timeout: 6000 })
    await expect(card(page, 233)).toHaveCount(0)
    await expect(card(page, 234)).toBeVisible()
    await expect(page.getByRole('link', { name: 'in reply to #233', exact: true })).toBeVisible()
    release.resolve()
    await expect(card(page, 233)).toBeVisible()
    await expect(page.getByRole('link', { name: 'in reply to #233', exact: true })).toHaveCount(0)
  } finally { release.resolve() }
})

test('an attached preview remains labelled beside a folded parent', async ({ page, host }) => {
  host.chain.blocklist = { registry: host.chain.contract, list: 'blocked' }
  await page.route('**/state', async route => {
    const memberships = route.request().postDataJSON().memberships
    if (!memberships?.length) return route.fallback()
    const answer = await (await host.answer(route.request())).json()
    answer.memberships = memberships.map(m => m.member.toLowerCase() === stranger.toLowerCase())
    await route.fulfill({ json: answer })
  })
  await setup(page, host, true)
  await card(page, 230).getByRole('button', { name: '1 more reply', exact: true }).click()
  await expect.poll(() => ids(page)).toEqual([230, 231, 233, 234])
  await expect(card(page, 233)).toHaveClass(/collapsed/)
  await expect(card(page, 233)).not.toHaveClass(/\bconnector\b/)
  await expect(card(page, 234)).toBeVisible()
  await expect(page.getByRole('link', { name: 'in reply to #233', exact: true })).toBeVisible()
  await card(page, 233).getByRole('button', { name: '[ show ]', exact: true }).click()
  await expect(page.getByRole('link', { name: 'in reply to #233', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: '[ open editor ]', exact: true }).click()
  await expect(page.getByRole('link', { name: 'in reply to #233', exact: true })).toBeVisible()
  await expect(card(page, 233)).not.toHaveClass(/collapsed/)
  await page.getByRole('button', { name: '[ close editor ]', exact: true }).click()
  await expect(card(page, 233)).not.toHaveClass(/collapsed/)
  await expect(page.getByRole('link', { name: 'in reply to #233', exact: true })).toHaveCount(0)
})
