import { test, expect, stranger, card } from './host.mjs'

for (const width of [1100, 390]) test(`opening context inherits previews and paged branches without changing the stream at ${width}px`, async ({ page, host }) => {
  await page.setViewportSize({ width, height: 850 })
  host.post(1, 'Earlier ancestor', { who: stranger })
  host.post(2, 'Visible parent', { who: stranger, parent: 1 })
  host.post(3, 'Automatic followed preview', { parent: 2 })
  for (let id = 4; id <= 28; id++) host.post(id, `Manually opened reply ${id}`, { who: stranger, parent: 3 })
  await page.goto('/')
  await card(page, 3).getByRole('button', { name: '25 replies', exact: true }).click()
  await expect(card(page, 23)).toBeVisible()
  await expect(card(page, 24)).toHaveCount(0)
  await page.getByRole('button', { name: /show \d+ more repl/ }).click()
  await expect(card(page, 24)).toBeVisible()
  await expect(card(page, 28)).toBeVisible()
  await expect(card(page, 24)).toBeVisible()
  await page.locator('.conversation-context[href="/p/84532/1"]').click()
  await expect(page).toHaveURL(/\/p\/84532\/1$/)
  await expect(card(page, 3)).toBeVisible()
  await expect(card(page, 28)).toBeVisible()
  await expect(card(page, 24)).toBeVisible()
  await card(page, 3).getByRole('button', { name: 'hide replies', exact: true }).click()
  await expect(card(page, 28)).toHaveCount(0)
  await page.getByRole('button', { name: 'back', exact: true }).click()
  await expect(page).toHaveURL(/\/$/)
  await expect(card(page, 28)).toBeVisible()
  await expect(card(page, 24)).toBeVisible()
  await expect(card(page, 3).getByRole('button', { name: 'hide replies', exact: true })).toBeVisible()
  await page.goBack()
  await expect(page).toHaveURL(/\/p\/84532\/1$/)
  await expect(card(page, 3)).toBeVisible()
  await expect(card(page, 28)).toHaveCount(0)
  await page.goForward()
  await expect(card(page, 28)).toBeVisible()
})

test('context keeps a visible branch beyond the parent thread first page without filling the gap', async ({ page, host }) => {
  host.post(1, 'Earlier ancestor', { who: stranger })
  for (let id = 2; id <= 25; id++) host.post(id, `Unfollowed sibling ${id}`, { who: stranger, parent: 1 })
  host.post(26, 'Followed reply below the last sibling', { parent: 25 })
  await page.goto('/')
  await expect(card(page, 26)).toBeVisible()
  const prevented = await page.evaluate(() => {
    let prevented
    // Suppress the browser's new tab only after the component has handled the event.
    document.addEventListener('click', event => { prevented = event.defaultPrevented; event.preventDefault() }, { once: true })
    document.querySelector('.conversation-context').dispatchEvent(new MouseEvent('click', { bubbles: true, cancelable: true, ctrlKey: true }))
    return prevented
  })
  expect(prevented).toBe(false)
  await expect(page).toHaveURL(/\/$/)
  await page.locator('.conversation-context[href="/p/84532/1"]').click()
  await expect(card(page, 25)).toBeVisible()
  await expect(card(page, 26)).toBeVisible()
  await expect(card(page, 22)).toHaveCount(0)
  await expect(page.getByRole('button', { name: /show .* more repl/ })).toBeVisible()
})

for (const width of [1100, 390]) for (const entry of ['card', 'permalink', 'full post']) test(`opening a stream ${entry} keeps its nested preview at ${width}px`, async ({ page, host }) => {
  await page.setViewportSize({ width, height: 850 })
  host.post(1, Array.from({ length: 20 }, (_, i) => `Parent line ${i}`).join('\n'))
  host.post(2, 'Visible direct reply', { parent: 1 })
  host.post(3, 'Visible nested reply', { parent: 2 })
  await page.goto('/')
  await expect(card(page, 3)).toBeVisible()
  if (entry === 'card') await card(page, 1).locator('.message-text').click({ position: { x: 30, y: 15 } })
  else if (entry === 'permalink') await card(page, 1).getByRole('link', { name: 'open post #1', exact: true }).click()
  else await card(page, 1).getByRole('link', { name: 'read full post', exact: true }).click()
  await expect(page).toHaveURL(/\/p\/84532\/1$/)
  await expect(card(page, 3)).toBeVisible()
  await card(page, 2).getByRole('button', { name: 'hide replies', exact: true }).click()
  await expect(card(page, 3)).toHaveCount(0)
  await page.getByRole('button', { name: 'back', exact: true }).click()
  await expect(card(page, 3)).toBeVisible()
})

for (const width of [1100, 390]) test(`opening a loaded stream reply keeps its nested choices at ${width}px`, async ({ page, host }) => {
  await page.setViewportSize({ width, height: 850 })
  host.post(1, 'Stream root')
  host.post(2, 'Loaded child', { who: stranger, parent: 1 })
  host.post(3, 'Loaded grandchild', { who: stranger, parent: 2 })
  host.post(4, 'Loaded final reply', { who: stranger, parent: 3 })
  await page.goto('/')
  for (const id of [1, 2, 3]) await card(page, id).getByRole('button', { name: '1 reply', exact: true }).click()
  await expect(card(page, 4)).toBeVisible()
  const link = card(page, 2).getByRole('link', { name: 'open post #2', exact: true })
  const prevented = await link.evaluate(element => {
    let prevented
    document.addEventListener('click', event => { prevented = event.defaultPrevented; event.preventDefault() }, { once: true })
    element.dispatchEvent(new MouseEvent('click', { bubbles: true, cancelable: true, ctrlKey: true }))
    return prevented
  })
  expect(prevented).toBe(false)
  await expect(page).toHaveURL(/\/$/)
  await link.click()
  await expect(page).toHaveURL(/\/p\/84532\/2$/)
  await expect(card(page, 4)).toBeVisible()
  await card(page, 3).getByRole('button', { name: 'hide replies', exact: true }).click()
  await expect(card(page, 4)).toHaveCount(0)
  await page.getByRole('button', { name: 'back', exact: true }).click()
  await expect(card(page, 4)).toBeVisible()
})
